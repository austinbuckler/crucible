import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type {
    DiscoveredRoute,
    FrameLevel,
    RouteSegment,
    ServerRoute,
} from "./scan.ts";
import { relPosix } from "./scan.ts";
import { parsePage, type ParsedPage } from "./parse.ts";
import { writeIfChanged } from "./write-if-changed.ts";

export type EmitContext = {
    appRoot: string;
    outDir: string;
    // npm specifier for the crucible package itself, used in generated
    // `import …` statements. Defaults to "react-crucible". Override when
    // the package is published or aliased under a different name.
    crucibleSpecifier: string;
};

// Filename of the optional user config module. When present, codegen
// imports it from the emitted main.tsx and passes its `network` export
// to `createEnvironment`. The file is the first user-export-drives-
// codegen surface in Crucible — keep its shape stable; future
// env-level options live alongside `network` in the same module.
const CONFIG_FILENAME = "crucible.config.ts";

export const DEFAULT_CRUCIBLE_SPECIFIER = "react-crucible";

export type RouteWithPage = {
    route: DiscoveredRoute;
    parsed: ParsedPage;
};

const HEADER = `// THIS FILE IS GENERATED BY CRUCIBLE — DO NOT EDIT.
// Re-run \`bun run codegen\` after changing routes or page Queries types.
`;

export function emitAll(
    ctx: EmitContext,
    routes: ReadonlyArray<RouteWithPage>,
): void {
    mkdirSync(ctx.outDir, { recursive: true });
    mkdirSync(join(ctx.outDir, "entrypoints"), { recursive: true });

    for (const r of routes) emitEntrypoint(ctx, r);
    emitRoutesManifest(ctx, routes);
}

// Emit the React entry that boots the app. Users own only `src/app/`;
// createRoot / StrictMode / AppShell / environment wiring all live here.
//
// App-wide values (theme color, default title, etc.) are NOT configured
// here — they belong in `src/app/layout.tsx`'s `metadata` export, which
// merges over AppShell's hardcoded defaults at render time.
//
// Configuration that has to reach framework primitives at boot lives in
// an optional `src/app/crucible.config.ts`:
//   - `network` (#46) — threaded into `createEnvironment` so consumers
//     can supply a custom fetch (Idempotency-Key wrapper, telemetry,
//     etc.) without monkey-patching `globalThis.fetch`.
//   - `localGraphQL` — converted into a fetch via
//     `createLocalGraphQLFetch` so Relay can execute against a local
//     Pothos/Drizzle/SQLite schema without knowing a sync engine exists.
//   - `swUpdate` (#53) — threaded into `<AppShell>` so consumers can
//     tune the SW update lifecycle (idle threshold, observability
//     callbacks) per the `SwUpdateBehavior` shape from #29.
//   - `persistence` — threaded into `createEnvironment` so apps can
//     scope or disable Relay RecordSource localStorage persistence without
//     hand-editing the generated bootstrap.
//
// Imports + props are conditional on which fields the user exports —
// apps that don't ship a config file get the original zero-config
// bundle; apps that ship a config but only export `network` get a
// bare `<AppShell>` (no swUpdate prop), and vice versa. This keeps
// the emitted main.tsx noise-free relative to actual config use.
/**
 * Emit `.crucible/server-routes.ts` — a Hono app that mounts every
 * `route.ts` file the user authored under `src/app/`, Next.js-style.
 * The user's `server.ts` imports this module and mounts it under `/`
 * (or wherever) on its top-level Hono app:
 *
 *   import serverRoutes from "./.crucible/server-routes.ts";
 *   app.route("/", serverRoutes);
 *
 * Empty when no `route.ts` files exist — emits an empty Hono app so
 * importing it never fails. Re-emitted on every codegen run; the
 * `writeIfChanged` guard keeps Vite's HMR quiet when the route set
 * hasn't changed.
 */
export function emitServerRoutes(
    ctx: EmitContext,
    routes: ReadonlyArray<ServerRoute>,
): void {
    const file = join(ctx.outDir, "server-routes.ts");
    const fileDir = dirname(file);

    const importLines = routes
        .map((r, i) => `import route${i} from "${relPosix(fileDir, r.file)}";`)
        .join("\n");

    const mountLines = routes
        .map((r, i) => `app.route(${JSON.stringify(r.urlPath)}, route${i});`)
        .join("\n");

    const content = `${HEADER}
import { Hono } from "hono";
${importLines}

const app = new Hono();
${mountLines}

export default app;
`;
    writeIfChanged(file, content);
}

export function emitMainEntry(ctx: EmitContext): void {
    const file = join(ctx.outDir, "main.tsx");
    const configPath = join(ctx.appRoot, "src", "app", CONFIG_FILENAME);
    const hasConfig = existsSync(configPath);
    const exports = hasConfig
        ? readConfigExports(configPath)
        : new Set<string>();
    const hasNetwork = exports.has("network");
    const hasLocalGraphQL = exports.has("localGraphQL");
    const hasSwUpdate = exports.has("swUpdate");
    const hasPersistence = exports.has("persistence");

    // Build the import line incrementally so we only name what the user
    // actually exports. This prevents a "no exported member" type error
    // if someone writes a config file that, say, only sets `swUpdate`.
    const importNames: string[] = [];
    if (hasNetwork) importNames.push("network as __cruxNetwork");
    if (hasLocalGraphQL) importNames.push("localGraphQL as __cruxLocalGraphQL");
    if (hasSwUpdate) importNames.push("swUpdate as __cruxSwUpdate");
    if (hasPersistence) importNames.push("persistence as __cruxPersistence");
    const configImport =
        importNames.length > 0
            ? `import { ${importNames.join(", ")} } from "../src/app/crucible.config.ts";\n`
            : "";
    const localGraphQLImport = hasLocalGraphQL
        ? `import { createLocalGraphQLFetch, createLocalGraphQLSubscribe, prepareLocalGraphQL } from "${ctx.crucibleSpecifier}/runtime/local-graphql.ts";\n`
        : "";

    const prepareLocalGraphQL = hasLocalGraphQL
        ? `if (__cruxLocalGraphQL) await prepareLocalGraphQL(__cruxLocalGraphQL);
`
        : "";
    const envSetup = hasLocalGraphQL
        ? hasNetwork
            ? `const __cruxFetch = __cruxLocalGraphQL ? createLocalGraphQLFetch(__cruxLocalGraphQL) : __cruxNetwork?.fetch;
const __cruxSubscribe = __cruxLocalGraphQL ? createLocalGraphQLSubscribe(__cruxLocalGraphQL) : __cruxNetwork?.subscribe;
const environment = Crucible.createEnvironment({ fetch: __cruxFetch, subscribe: __cruxSubscribe, persistStore: ${hasPersistence ? "__cruxPersistence?.persistStore ?? " : ""}(__cruxLocalGraphQL ? false : true), storeScope: ${hasPersistence ? "__cruxPersistence?.scope" : "undefined"} });`
            : `const environment = Crucible.createEnvironment({ fetch: __cruxLocalGraphQL ? createLocalGraphQLFetch(__cruxLocalGraphQL) : undefined, subscribe: __cruxLocalGraphQL ? createLocalGraphQLSubscribe(__cruxLocalGraphQL) : undefined, persistStore: ${hasPersistence ? "__cruxPersistence?.persistStore ?? " : ""}(__cruxLocalGraphQL ? false : true), storeScope: ${hasPersistence ? "__cruxPersistence?.scope" : "undefined"} });`
        : hasNetwork
          ? `const environment = Crucible.createEnvironment({ fetch: __cruxNetwork?.fetch, subscribe: __cruxNetwork?.subscribe${hasPersistence ? ", persistStore: __cruxPersistence?.persistStore, storeScope: __cruxPersistence?.scope" : ""} });`
          : hasPersistence
            ? `const environment = Crucible.createEnvironment({ persistStore: __cruxPersistence?.persistStore, storeScope: __cruxPersistence?.scope });`
          : `const environment = Crucible.createEnvironment();`;
    const appShellOpen = hasSwUpdate
        ? `<Crucible.AppShell swUpdate={__cruxSwUpdate}>`
        : `<Crucible.AppShell>`;

    const content = `${HEADER}
import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import * as Crucible from "${ctx.crucibleSpecifier}/crucible";
import { routes } from "./routes.ts";
${configImport}
${localGraphQLImport}
${prepareLocalGraphQL}${envSetup}

createRoot(document.getElementById("root")!).render(
  <StrictMode>
    ${appShellOpen}
      <Crucible.App routes={routes} environment={environment} />
    </Crucible.AppShell>
  </StrictMode>,
);
`;
    writeIfChanged(file, content);
}

// Read the user's `crucible.config.ts` source and return the set of
// top-level export names we recognize. We do a syntactic scan rather
// than a full TypeScript compile here for two reasons: (a) codegen
// runs every dev-server boot and on every file save, so it must be
// cheap; (b) we only care about a few specific names — detecting them
// via regex is reliable for the patterns this file is
// expected to hold (`export const network = …`, `export const
// localGraphQL = …`, `export const swUpdate = …`, occasionally re-exports). If a user resorts to
// dynamic exports the codegen will simply not detect them and the
// emitted main.tsx will lack the corresponding wiring; that's a
// reasonable footgun cost for keeping codegen fast and synchronous.
function readConfigExports(configPath: string): Set<string> {
    const found = new Set<string>();
    let source: string;
    try {
        source = readFileSync(configPath, "utf8");
    } catch {
        return found;
    }
    source = stripCommentsAndStrings(source);
    // Recognize:
    //   export const X = …
    //   export let X = …
    //   export var X = …
    //   export { X }              ← bare re-export of a local binding
    //   export { foo as X }       ← aliased re-export
    // Only the known config-shape names are checked.
    const known = ["network", "localGraphQL", "swUpdate", "persistence"] as const;
    for (const name of known) {
        if (hasDirectExportDeclaration(source, name) || hasNamedExport(source, name)) {
            found.add(name);
        }
    }
    return found;
}

function hasDirectExportDeclaration(source: string, name: string): boolean {
    const directDecl = /\bexport\s+(?:const|let|var)\s+/g;
    for (const match of source.matchAll(directDecl)) {
        const declaration = readDirectExportDeclaration(source, match.index + match[0].length);
        for (const declarator of splitTopLevelDeclarators(declaration)) {
            if (new RegExp(`^\\s*${name}\\b`).test(declarator)) return true;
        }
    }
    return false;
}

function readDirectExportDeclaration(source: string, start: number): string {
    let depth = 0;
    for (let i = start; i < source.length; i++) {
        const ch = source[i];
        if (ch === "{" || ch === "[" || ch === "(") depth++;
        if (ch === "}" || ch === "]" || ch === ")") depth = Math.max(0, depth - 1);
        if (depth === 0 && ch === ";") return source.slice(start, i);
        if (
            depth === 0 &&
            ch === "\n" &&
            !source.slice(start, i).trimEnd().endsWith(",") &&
            !/[=({[?:+\-*/&|.]$/.test(source.slice(start, i).trimEnd()) &&
            !/^\s*,/.test(source.slice(i + 1))
        ) {
            return source.slice(start, i);
        }
        if (depth === 0 && ch === "\n" && /^\s*export\b/.test(source.slice(i + 1))) {
            return source.slice(start, i);
        }
    }
    return source.slice(start);
}

function splitTopLevelDeclarators(declaration: string): string[] {
    const parts: string[] = [];
    let start = 0;
    let depth = 0;
    for (let i = 0; i < declaration.length; i++) {
        const ch = declaration[i];
        if (ch === "{" || ch === "[" || ch === "(") depth++;
        if (ch === "}" || ch === "]" || ch === ")") depth = Math.max(0, depth - 1);
        if (ch === "," && depth === 0) {
            parts.push(declaration.slice(start, i));
            start = i + 1;
        }
    }
    parts.push(declaration.slice(start));
    return parts;
}

function hasNamedExport(source: string, name: string): boolean {
    const exportBlock = /\bexport\s*\{([^}]*)\}/g;
    for (const match of source.matchAll(exportBlock)) {
        const specifiers = (match[1] ?? "").split(",");
        for (const specifier of specifiers) {
            const parts = specifier.trim().split(/\s+as\s+/);
            const exportedName = (parts[1] ?? parts[0])?.trim();
            if (exportedName === name) return true;
        }
    }
    return false;
}

function stripCommentsAndStrings(source: string): string {
    let out = "";
    for (let i = 0; i < source.length; i++) {
        const ch = source[i];
        const next = source[i + 1];

        if (ch === "/" && next === "/") {
            out += "  ";
            i += 2;
            while (i < source.length && source[i] !== "\n") {
                out += " ";
                i++;
            }
            if (i < source.length) out += source[i];
            continue;
        }

        if (ch === "/" && next === "*") {
            out += "  ";
            i += 2;
            while (i < source.length) {
                if (source[i] === "*" && source[i + 1] === "/") {
                    out += "  ";
                    i++;
                    break;
                }
                out += source[i] === "\n" ? "\n" : " ";
                i++;
            }
            continue;
        }

        if (ch === '"' || ch === "'" || ch === "`") {
            const quote = ch;
            out += " ";
            while (++i < source.length) {
                const current = source[i];
                out += current === "\n" ? "\n" : " ";
                if (current === "\\") {
                    if (i + 1 < source.length) {
                        i++;
                        out += source[i] === "\n" ? "\n" : " ";
                    }
                    continue;
                }
                if (current === quote) break;
            }
            continue;
        }

        if (ch === "/" && isRegexLiteralStart(out)) {
            out += " ";
            let inClass = false;
            while (++i < source.length) {
                const current = source[i];
                out += current === "\n" ? "\n" : " ";
                if (current === "\\") {
                    if (i + 1 < source.length) {
                        i++;
                        out += source[i] === "\n" ? "\n" : " ";
                    }
                    continue;
                }
                if (current === "[") inClass = true;
                if (current === "]") inClass = false;
                if (current === "/" && !inClass) {
                    while (/[a-z]/i.test(source[i + 1] ?? "")) {
                        i++;
                        out += " ";
                    }
                    break;
                }
            }
            continue;
        }

        out += ch;
    }
    return out;
}

function isRegexLiteralStart(strippedPrefix: string): boolean {
    const trimmed = strippedPrefix.trimEnd();
    if (trimmed.length === 0) return true;
    if (/(^|[^\w$])(?:return|throw|case|delete|typeof|void|new|yield)$/.test(trimmed)) {
        return true;
    }
    const prev = trimmed[trimmed.length - 1];
    return prev != null && "([{=,:;!&|?+-*~^<>".includes(prev);
}

function emitEntrypoint(ctx: EmitContext, rwp: RouteWithPage): void {
    const file = join(ctx.outDir, "entrypoints", `${rwp.route.id}.ts`);
    const segments = rwp.route.segments;
    emitEntrypointModule({
        outFile: file,
        sourceFile: rwp.route.pageFile,
        parsed: rwp.parsed,
        segments,
        id: rwp.route.id,
        crucibleSpecifier: ctx.crucibleSpecifier,
    });
}

type EmitModuleOpts = {
    outFile: string;
    sourceFile: string;
    parsed: ParsedPage;
    segments: ReadonlyArray<RouteSegment>;
    id: string;
    crucibleSpecifier: string;
};

function emitEntrypointModule(opts: EmitModuleOpts): void {
    const fileDir = dirname(opts.outFile);
    const sourcePathRel = relPosix(fileDir, opts.sourceFile);

    // Two runtime handles per query, intentionally split across two artifacts:
    //   - VALUE: `<Op>$parameters.ts` — relay-compiler's preload header
    //     (operation id + name + kind, ~20 lines). Tiny.
    //   - LAZY VALUE: `<Op>.graphql.ts` — the full normalized AST + client
    //     resolver imports. Heavy, so keep it behind JSResource, but warm it
    //     at navigation time independently from the page component chunk.
    //
    // The page module itself still imports `.graphql.ts` for
    // `usePreloadedQuery(graphql\`...\`, queries.x)`. The separate artifact
    // resource prevents a hidden waterfall for queries with Relay client
    // resolvers: Relay can start the network from `$parameters.ts`, while
    // the full operation/client-resolver artifact loads in parallel with the
    // page chunk instead of being discovered only after the page import.
    //
    // `$parameters.ts` is only emitted for queries marked `@preloadable`.
    // Pages must declare their queries as preloadable (Crucible's
    // convention enforces this anyway) — if a query isn't preloadable,
    // codegen fails at relay-compile, not here.
    const queryImports = opts.parsed.queries
        .map((q, i) => {
            const stem = q.artifactPath.replace(/\.graphql$/, "");
            const parametersRel =
                relPosix(fileDir, `${stem}$parameters`) + ".ts";
            const typeRel = relPosix(fileDir, q.artifactPath) + ".ts";
            return `import query${i} from "${parametersRel}";\nimport type { ${q.artifactExport} } from "${typeRel}";\nconst queryArtifact${i} = JSResource("${opts.id}.query${i}", () => import("${typeRel}") as Promise<{ default: import("relay-runtime").ConcreteRequest }>);`;
        })
        .join("\n");

    const paramNames = new Set<string>();
    for (const seg of opts.segments) {
        if (seg.kind === "param" || seg.kind === "catchall")
            paramNames.add(seg.name);
    }

    let usesParams = false;
    const queryEntries = opts.parsed.queries
        .map((q, i) => {
            const vars =
                opts.parsed.operationVariables.get(q.artifactExport) ?? [];
            const mapped = vars.filter((v) => paramNames.has(v));
            if (mapped.length > 0) usesParams = true;
            const variablesLiteral =
                mapped.length === 0
                    ? "{}"
                    : `{ ${mapped.map((v) => `${v}: params.${v}`).join(", ")} }`;
            return `      ${q.fieldName}: { parameters: query${i}, artifact: queryArtifact${i}, variables: ${variablesLiteral} },`;
        })
        .join("\n");

    const preloadParam = usesParams ? "{ params }" : "_preload";

    const queriesType = opts.parsed.queries.length
        ? `{
${opts.parsed.queries
    .map(
        (q, i) =>
            `      ${q.fieldName}: { parameters: typeof query${i}; artifact: typeof queryArtifact${i}; variables: ${q.artifactExport}["variables"] };`,
    )
    .join("\n")}
    }`
        : "Record<string, never>";

    // Page modules receive the unwrapped `data` (the single @preloadable
    // PreloadedQuery), `params`, and validated `search`.
    const dataField = opts.parsed.queries.length
        ? `data: Queries["data"]["parameters"] extends infer P ? import("react-relay").PreloadedQuery<${
              opts.parsed.queries[0]!.artifactExport
          }> : never`
        : `data: undefined`;
    const moduleType = `Promise<{
        default: ComponentType<{ ${dataField}; params: any; search: any }>;
      }>`;

    const standardSchemaImport = "";

    const content = `${HEADER}
import { JSResource, type EntryPoint } from "${opts.crucibleSpecifier}/runtime/entrypoint.ts";
import type { ComponentType } from "react";
import type { Metadata } from "${opts.crucibleSpecifier}/runtime/metadata.tsx";
${standardSchemaImport}${queryImports}

type Queries = ${queriesType};

const entrypoint: EntryPoint<Queries> = {
  root: JSResource(
    "${opts.id}",
    () =>
      import("${sourcePathRel}") as ${moduleType},
  ),
  getPreloadProps: (${preloadParam}) => ({
    queries: {
${queryEntries}
    } as Queries,
  }),
};

export default entrypoint;
`;
    writeIfChanged(opts.outFile, content);
}

type ResourceRegistry = {
    imports: string[];
    // file → resource ident (e.g. layout0)
    byFile: Map<string, string>;
    counters: Record<string, number>;
};

function makeRegistry(): ResourceRegistry {
    return { imports: [], byFile: new Map(), counters: {} };
}

function frameResources(
    reg: ResourceRegistry,
    frame: FrameLevel,
    fileDir: string,
): { layout?: string; loading?: string; error?: string; notFound?: string } {
    const out: ReturnType<typeof frameResources> = {};

    // Layouts code-split alongside the page chunk (both wait for the same
    // navigation), so they're lazy via JSResource. Boundary fallbacks must
    // render synchronously when their boundary fires — a Suspense fallback
    // can't itself suspend — so they're imported eagerly.
    if (frame.layout) {
        let ident = reg.byFile.get(frame.layout);
        if (!ident) {
            const counter = reg.counters["layout"] ?? 0;
            reg.counters["layout"] = counter + 1;
            ident = `layout${counter}`;
            reg.byFile.set(frame.layout, ident);
            const rel = relPosix(fileDir, frame.layout);
            reg.imports.push(
                `const ${ident} = JSResource("${ident}", () => import("${rel}") as Promise<{ default: ComponentType<{ children: ReactNode } & Record<string, ReactNode>>; metadata?: Metadata }>);`,
            );
        }
        out.layout = ident;
    }

    const eagerSlots: ReadonlyArray<{
        key: "loading" | "error" | "notFound";
        kind: string;
    }> = [
        { key: "loading", kind: "loading" },
        { key: "error", kind: "error" },
        { key: "notFound", kind: "notFound" },
    ];
    for (const slot of eagerSlots) {
        const file = frame[slot.key];
        if (!file) continue;
        let ident = reg.byFile.get(file);
        if (!ident) {
            const counter = reg.counters[slot.kind] ?? 0;
            reg.counters[slot.kind] = counter + 1;
            ident = `${slot.kind}${counter}`;
            reg.byFile.set(file, ident);
            const rel = relPosix(fileDir, file);
            reg.imports.push(`import ${ident} from "${rel}";`);
        }
        out[slot.key] = ident;
    }
    return out;
}

function emitRoutesManifest(
    ctx: EmitContext,
    routes: ReadonlyArray<RouteWithPage>,
): void {
    const file = join(ctx.outDir, "routes.ts");
    const fileDir = dirname(file);

    const segmentsLiteral = (rwp: RouteWithPage) =>
        `[${rwp.route.segments
            .map((s) => {
                if (s.kind === "literal")
                    return `{ kind: "literal", value: ${JSON.stringify(s.value)} }`;
                if (s.kind === "param")
                    return `{ kind: "param", name: ${JSON.stringify(s.name)} }`;
                return `{ kind: "catchall", name: ${JSON.stringify(s.name)} }`;
            })
            .join(", ")}]`;

    const reg = makeRegistry();
    const routeBlocks = routes.map((rwp) => {
        const frameLines = rwp.route.frames.map((frame) => {
            const r = frameResources(reg, frame, fileDir);
            const props: string[] = [];
            if (r.layout) props.push(`layout: ${r.layout}`);
            if (r.loading) props.push(`loading: ${r.loading}`);
            if (r.error) props.push(`error: ${r.error}`);
            if (r.notFound) props.push(`notFound: ${r.notFound}`);
            if (frame.slots && frame.slots.length > 0)
                props.push(`slots: ${JSON.stringify(frame.slots)}`);
            props.push(`urlDepth: ${frame.urlDepth}`);
            return `      { ${props.join(", ")} }`;
        });
        const slotProp = rwp.route.slot
            ? `\n    slot: ${JSON.stringify(rwp.route.slot)},`
            : "";
        const interceptProp = rwp.route.intercept
            ? `\n    intercept: ${JSON.stringify(rwp.route.intercept)},`
            : "";
        const kindProp =
            rwp.route.kind === "default" ? `\n    kind: "default",` : "";
        return `  {
    path: ${JSON.stringify(rwp.route.urlPath)},
    segments: ${segmentsLiteral(rwp)},
    frames: [
${frameLines.join(",\n")}
    ],
    entrypoint: ${jsId(rwp.route.id)},${slotProp}${interceptProp}${kindProp}
  },`;
    });

    const entrypointImports = routes
        .map(
            (rwp) =>
                `import ${jsId(rwp.route.id)} from "./entrypoints/${rwp.route.id}.ts";`,
        )
        .join("\n");

    const content = `${HEADER}
import type { ComponentType, ReactNode } from "react";
import { JSResource } from "${ctx.crucibleSpecifier}/runtime/entrypoint.ts";
import type { RouteRecord } from "${ctx.crucibleSpecifier}/runtime/router/types.ts";
import type { Metadata } from "${ctx.crucibleSpecifier}/runtime/metadata.tsx";
${entrypointImports}

${reg.imports.join("\n")}

export const routes: ReadonlyArray<RouteRecord> = [
${routeBlocks.join("\n")}
];
`;
    writeIfChanged(file, content);
}

function jsId(routeId: string): string {
    return "ep_" + routeId.replace(/[^a-zA-Z0-9]/g, "_");
}
